"""Task 09A: ADMIN-only aggregate dashboard integration tests."""
import uuid

from fastapi.testclient import TestClient
from sqlalchemy import select

from app.core.database import SessionLocal
from app.core.security import hash_password
from app.main import app
from app.models.application import JobApplication, JobApplicationStatus
from app.models.cv import CV
from app.models.cv_template import CVTemplate, CVTemplateLayoutKey
from app.models.job import Job, JobStatus
from app.models.user import User, UserRole


client = TestClient(app)
BASE = "/api/v1/admin/dashboard"


def _headers(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}"}


def _token(role: str = "CANDIDATE") -> str:
    email = f"task09a_{uuid.uuid4().hex[:12]}@example.com"
    registered = client.post("/api/v1/auth/register", json={"email": email, "password": "password123", "full_name": "Task 09A", "role": role})
    assert registered.status_code == 201, registered.text
    response = client.post("/api/v1/auth/login", json={"email": email, "password": "password123"})
    assert response.status_code == 200, response.text
    return response.json()["access_token"]


def _admin_token() -> str:
    email = f"task09a_admin_{uuid.uuid4().hex[:12]}@example.com"
    db = SessionLocal()
    try:
        db.add(User(email=email, password_hash=hash_password("password123"), full_name="Task 09A Admin", role=UserRole.ADMIN))
        db.commit()
    finally:
        db.close()
    response = client.post("/api/v1/auth/login", json={"email": email, "password": "password123"})
    assert response.status_code == 200, response.text
    return response.json()["access_token"]


def _dashboard(token: str) -> dict:
    response = client.get(BASE, headers=_headers(token))
    assert response.status_code == 200, response.text
    return response.json()


def _cleanup_task_records() -> None:
    """Remove only data generated by this integration test suite."""
    db = SessionLocal()
    try:
        user_ids = list(db.scalars(select(User.id).where(User.email.like("task09a_%@example.com"))))
        if user_ids:
            db.query(JobApplication).filter(JobApplication.candidate_id.in_(user_ids)).delete(synchronize_session=False)
            db.query(CV).filter(CV.candidate_id.in_(user_ids)).delete(synchronize_session=False)
        db.query(Job).filter(Job.title.like(r"\_\_task09a\_\_%", escape="\\")).delete(synchronize_session=False)
        db.query(CVTemplate).filter(CVTemplate.name.like(r"\_\_task09a\_\_%", escape="\\")).delete(synchronize_session=False)
        if user_ids:
            db.query(User).filter(User.id.in_(user_ids)).delete(synchronize_session=False)
        db.commit()
    finally:
        db.close()


def test_dashboard_requires_admin_role():
    try:
        assert client.get(BASE).status_code == 401
        assert client.get(BASE, headers=_headers(_token("CANDIDATE"))).status_code == 403
        assert client.get(BASE, headers=_headers(_token("RECRUITER"))).status_code == 403
        assert client.get(BASE, headers=_headers(_admin_token())).status_code == 200
    finally:
        _cleanup_task_records()


def test_dashboard_aggregates_all_metrics_and_keeps_complete_zero_safe_shape():
    admin_token = _admin_token()
    before = _dashboard(admin_token)
    db = SessionLocal()
    try:
        active_candidates = [
            User(email=f"task09a_candidate_{uuid.uuid4().hex}@example.com", password_hash="test", full_name="Candidate", role=UserRole.CANDIDATE)
            for _ in JobApplicationStatus
        ]
        extra_users = [
            User(email=f"task09a_inactive_candidate_{uuid.uuid4().hex}@example.com", password_hash="test", full_name="Inactive Candidate", role=UserRole.CANDIDATE, is_active=False),
            User(email=f"task09a_recruiter_{uuid.uuid4().hex}@example.com", password_hash="test", full_name="Recruiter", role=UserRole.RECRUITER),
            User(email=f"task09a_inactive_recruiter_{uuid.uuid4().hex}@example.com", password_hash="test", full_name="Inactive Recruiter", role=UserRole.RECRUITER, is_active=False),
        ]
        inactive_template = CVTemplate(id=uuid.uuid4(), name=f"__task09a__ inactive {uuid.uuid4().hex}", layout_key=CVTemplateLayoutKey.MINIMAL, is_active=False, sort_order=999)
        active_template = CVTemplate(id=uuid.uuid4(), name=f"__task09a__ active {uuid.uuid4().hex}", layout_key=CVTemplateLayoutKey.CLASSIC, is_active=True, sort_order=999)
        jobs = [Job(title=f"__task09a__ {job_status.value} {uuid.uuid4().hex}", description="Aggregate test", company_name="GJob", status=job_status) for job_status in JobStatus]
        db.add_all([*active_candidates, *extra_users, inactive_template, active_template, *jobs])
        db.flush()
        cvs = [CV(candidate_id=candidate.id, template_id=active_template.id, title="Dashboard CV") for candidate in active_candidates]
        approved_job = next(job for job in jobs if job.status == JobStatus.APPROVED)
        db.add_all(cvs)
        db.flush()
        applications = [
            JobApplication(job_id=approved_job.id, candidate_id=candidate.id, cv_id=cv.id, status=application_status)
            for candidate, cv, application_status in zip(active_candidates, cvs, JobApplicationStatus, strict=True)
        ]
        db.add_all(applications)
        db.commit()
    finally:
        db.close()

    try:
        after = _dashboard(admin_token)
        assert after["users"]["total"] == before["users"]["total"] + len(active_candidates) + len(extra_users)
        assert after["users"]["candidates"] == before["users"]["candidates"] + len(active_candidates) + 1
        assert after["users"]["recruiters"] == before["users"]["recruiters"] + 2
        assert after["users"]["admins"] == before["users"]["admins"]
        assert after["users"]["active"] == before["users"]["active"] + len(active_candidates) + 1
        assert after["users"]["inactive"] == before["users"]["inactive"] + 2

        assert after["jobs"]["total"] == before["jobs"]["total"] + len(jobs)
        for job_status in JobStatus:
            assert after["jobs"][job_status.value.lower()] == before["jobs"][job_status.value.lower()] + 1

        assert after["applications"]["total"] == before["applications"]["total"] + len(applications)
        for application_status in JobApplicationStatus:
            assert after["applications"][application_status.value.lower()] == before["applications"][application_status.value.lower()] + 1

        assert after["cvs"]["total"] == before["cvs"]["total"] + len(cvs)
        assert after["cv_templates"]["total"] == before["cv_templates"]["total"] + 2
        assert after["cv_templates"]["active"] == before["cv_templates"]["active"] + 1
        assert after["cv_templates"]["inactive"] == before["cv_templates"]["inactive"] + 1

        assert set(after["users"]) == {"total", "candidates", "recruiters", "admins", "active", "inactive"}
        assert set(after["jobs"]) == {"total", "pending", "approved", "rejected", "closed"}
        assert set(after["applications"]) == {"total", "submitted", "reviewing", "shortlisted", "rejected", "hired", "withdrawn"}
    finally:
        _cleanup_task_records()
